// Writes plugin/src/gen/LxrData.h: every table, constant and parameter layout the C++ engine needs, read from the
// web app's own modules (engine/, sound/), so data and layout changes in the JS reach the plugin without porting.
// Only logic changes need porting by hand (plugin/test/parity.mjs finds them). Run: node plugin/tools/gen-data.mjs
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as T from '../../engine/lxr-tables.js';
import { EXTRA_CLICKS } from '../../engine/lxr-clicks.js';
import * as E from '../../engine/lxr.js';
import * as S from '../../sound/schema.js';
import { FX_DEFAULTS, ECHO_DIVS } from '../../sound/instrument.js';
import { GATES } from '../../sound/makers.js';
import { TABLE_IDS } from '../../sound/tables.js';
import { BUILTIN_IDS } from '../../engine/wavetables.js';

const out = [];
const w = (s) => out.push(s);
const num = (x) => { if (Number.isInteger(x)) return String(x); const s = String(x); return /[e.]/.test(s) ? s : s + '.0'; };
const arr = (type, name, a, per = 24) => {
  const v = Array.from(a, (x) => (type === 'float' ? `${Object.is(x, -0) ? '-0.0' : num(x)}f` : type === 'double' ? num(x) : String(x)));
  const rows = []; for (let i = 0; i < v.length; i += per) rows.push('  ' + v.slice(i, i + per).join(', '));
  w(`inline const ${type} ${name}[${v.length}] = {\n${rows.join(',\n')}\n};`);
};
const ident = (s) => s.replace(/[^A-Za-z0-9_]/g, '_');

w('// Generated by plugin/tools/gen-data.mjs from engine/ and sound/. Do not edit.');
w('#pragma once');
w('#include <cstdint>');
w('namespace lxr::data {');
// ---- engine/lxr-tables.js ----
arr('int16_t', 'SINE_TABLE', T.SINE_TABLE);
arr('int16_t', 'TRI_TABLE', T.TRI_TABLE);
arr('int16_t', 'REC_TABLE', T.REC_TABLE);
arr('int16_t', 'SAW_TABLE', T.SAW_TABLE);
arr('int8_t', 'TRANSIENT_DATA', T.TRANSIENT_DATA);
// (Float32Array values, written as the doubles they are: exact)
arr('double', 'MIDI_NOTE_FREQ', T.MIDI_NOTE_FREQ);
arr('uint8_t', 'INIT_KIT', T.INIT_KIT);
arr('uint8_t', 'PARAMETER_ORDER', T.PARAMETER_ORDER);
for (const [k, v] of Object.entries(T.PAR)) w(`constexpr int PAR_${ident(k)} = ${v};`);
for (const [k, v] of Object.entries(T.CC)) w(`constexpr int CC_${ident(k)} = ${v};`);
for (const [k, v] of Object.entries(T.CC2)) w(`constexpr int CC2_${ident(k)} = ${v};`);
// ---- engine/lxr-clicks.js ----
EXTRA_CLICKS.forEach((c, i) => arr('int16_t', `CLICK_${i}`, c));
w(`inline const int16_t* const EXTRA_CLICKS[${EXTRA_CLICKS.length}] = { ${EXTRA_CLICKS.map((_, i) => `CLICK_${i}`).join(', ')} };`);
w(`inline const int EXTRA_CLICK_LEN[${EXTRA_CLICKS.length}] = { ${EXTRA_CLICKS.map((c) => c.length).join(', ')} };`);
w(`constexpr int NUM_EXTRA_CLICKS = ${EXTRA_CLICKS.length};`);
// ---- engine/lxr.js: which parameters modulation reaches, and the morphable switches ----
const NP = T.PAR.NUM_PARAMS ?? S.NUM_PARAMS;
const modulatable = new Uint8Array(256); for (const p of E.MODULATABLE) if (p !== undefined) modulatable[p] = 1;
arr('uint8_t', 'MODULATABLE', modulatable, 32);
const posKind = new Uint8Array(256); for (const [p, k] of E.POS_KIND) posKind[p] = { wave: 1, filter: 2, mode: 3 }[k];
arr('uint8_t', 'POS_KIND', posKind, 32);
w(`constexpr int NUM_PARAMS = ${S.NUM_PARAMS};`);
w(`constexpr int END_OF_SOUND_PARAMETERS = ${T.PAR.END_OF_SOUND_PARAMETERS};`);
w(`constexpr int PAR_NUM_PARAMS_ARRAY = ${NP};`);
// ---- sound/schema.js: the parameter layout past the firmware's ----
for (const k of ['SEND_BASE', 'REPEAT_BASE', 'SEQ_ON_BASE', 'SEQ_PAT_BASE', 'TRIM_BASE', 'TRIM_ZERO', 'EXTRA_BASE', 'NUM_EXTRAS', 'MOD_BASE',
  'MOD_AMT_ZERO', 'TABLE_BASE', 'DEPTH_BASE', 'STEP_BASE', 'STEPX_BASE', 'STEP2_BASE', 'STEPLEN_BASE', 'ALL_PARAMS', 'MAX_ENGINES']) w(`constexpr int ${k} = ${S[k]};`);
w(`constexpr double TRIM_STEP_DB = ${num(S.TRIM_STEP_DB)};`);
const live = new Uint8Array(S.ALL_PARAMS); for (const p of S.EXTRA_LIVE) live[p] = 1;
arr('uint8_t', 'EXTRA_LIVE', live, 48);
// the depths: par - DEPTH_BASE -> voice, dest, src (voice -1: none)
const routes = []; for (let p = S.DEPTH_BASE; p < S.STEP_BASE; p++) { const r = S.routeOf(p); routes.push(r && r.dest >= 0 ? [r.voice, r.dest, r.src] : [-1, -1, 0]); }
w('struct Route { int voice, dest, src; };');
// the knobs that can be modulated (for the MACRO knobs' targets, by name)
w(`constexpr int NUM_MOD = ${S.NUM_MOD};`); w(`constexpr int NUM_SRC = ${S.NUM_SRC};`);
w(`inline const char* const MOD_DIALS[${S.NUM_MOD}] = { ${S.MOD_DIALS.map((u) => JSON.stringify(u)).join(', ')} };`);
w(`inline const Route ROUTES[${routes.length}] = {\n${routes.map((r) => `  {${r.join(', ')}}`).join(',\n')}\n};`);
w(`inline const int SOUND_ENGINE_VOICE[6] = { ${S.SOUNDS.map((s) => s.engineVoice).join(', ')} };`);
w(`inline const int SOUND_TRIGGER[6] = { ${S.SOUNDS.map((s) => s.trigger).join(', ')} };`);
// each voice's controls, for MORPH TIME's blend (sound/makers.js blend): par, a knob (slides) or not (flips), max
w('struct SchemaEntry { int par; bool knob; double max; };');
const isKnob = (e) => e.display.type === 'num' || e.display.type === 'pm' || e.display.type === 'detent';
S.VOICE_SCHEMAS.forEach((sc, v) => w(`inline const SchemaEntry SCHEMA_${v}[${sc.length}] = {\n${sc.map((e) => `  {${e.par}, ${isKnob(e)}, ${num(e.max)}}`).join(',\n')}\n};`));
w(`inline const SchemaEntry* const SCHEMAS[6] = { ${S.VOICE_SCHEMAS.map((_, v) => `SCHEMA_${v}`).join(', ')} };`);
w(`inline const int SCHEMA_LEN[6] = { ${S.VOICE_SCHEMAS.map((sc) => sc.length).join(', ')} };`);
// GATES: a gate control and the parts that follow it, as parameters per voice (gate par, then parts, -1 ends a gate)
S.VOICE_SCHEMAS.forEach((sc, v) => {
  const byU = new Map(sc.map((e) => [e.ukey, e])), g = [];
  for (const [gate, parts] of Object.entries(GATES)) { const e = byU.get(gate); if (!e) continue; g.push(e.par); for (const u of parts) { const q = byU.get(u); if (q) g.push(q.par); } g.push(-1); }
  arr('int', `GATES_${v}`, g.length ? g : [-2]);
});
const glen = S.VOICE_SCHEMAS.map((sc) => { const byU = new Map(sc.map((e) => [e.ukey, e])); let n = 0; for (const [gate, parts] of Object.entries(GATES)) { if (!byU.get(gate)) continue; n += 2 + parts.filter((u) => byU.get(u)).length; } return n; });
w(`inline const int GATES_LEN[6] = { ${glen.join(', ')} };`);
w(`inline const int* const GATES[6] = { ${S.VOICE_SCHEMAS.map((_, v) => `GATES_${v}`).join(', ')} };`);
// ---- the wavetables: TABLE value i -> built-in table index (-1: CLASSIC) ----
w(`inline const int TABLE_BUILTIN[${TABLE_IDS.length}] = { ${TABLE_IDS.map((id) => (id ? BUILTIN_IDS.indexOf(id) : -1)).join(', ')} };`);
w(`constexpr int NUM_TABLE_IDS = ${TABLE_IDS.length};`);
// ---- sound/instrument.js ----
w(`inline const char* const FX_DEFAULTS_JSON = R"(${JSON.stringify(FX_DEFAULTS)})";`);
arr('double', 'ECHO_DIV_BEATS', ECHO_DIVS.map((d) => d[1]));
w('}');
const file = fileURLToPath(new URL('../src/gen/LxrData.h', import.meta.url));
fs.mkdirSync(new URL('../src/gen/', import.meta.url), { recursive: true });
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`LxrData.h: ${(fs.statSync(file).size / 1024).toFixed(0)} KB`);
