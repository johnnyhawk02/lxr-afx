// node tools/click-map.mjs: writes sound/click-map.js, each of the old sampled clicks (the firmware's 12 transients and
// the 22 extra clicks) as the nearest METAMORF click (engine/click.js): SHAPE, TONE and LENGTH, found by comparing their
// spectra (third-octave bands) and lengths, and the LEVEL that gives the same energy. At their own speed (CLICK FREQ's
// rate 1); a faster or slower play scales TONE up and LENGTH down (sound/clickmap.js oldClick).
import fs from 'node:fs';
import { TRANSIENT_DATA } from '../engine/lxr-tables.js';
import { EXTRA_CLICKS } from '../engine/lxr-clicks.js';
import { Click, clickTone, clickLen } from '../engine/click.js';
import { REAL_FS } from '../engine/lxr.js';

const N = 4096, FS = REAL_FS;
// third-octave bands, 60 Hz .. 18 kHz
const BANDS = []; for (let f = 60; f < 18000; f *= Math.pow(2, 1 / 3)) BANDS.push([f / Math.pow(2, 1 / 6), f * Math.pow(2, 1 / 6)]);
function fft(re, im) {
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) { let b = n >> 1; for (; j & b; b >>= 1) j ^= b; j ^= b; if (i < j) { [re[i], re[j]] = [re[j], re[i]]; [im[i], im[j]] = [im[j], im[i]]; } }
  for (let len = 2; len <= n; len <<= 1) {
    const a = -2 * Math.PI / len, wr = Math.cos(a), wi = Math.sin(a);
    for (let i = 0; i < n; i += len) {
      let cr = 1, ci = 0;
      for (let k = 0; k < len / 2; k++) {
        const p = i + k, q = p + len / 2, tr = re[q] * cr - im[q] * ci, ti = re[q] * ci + im[q] * cr;
        re[q] = re[p] - tr; im[q] = im[p] - ti; re[p] += tr; im[p] += ti;
        const t = cr * wr - ci * wi; ci = cr * wi + ci * wr; cr = t;
      }
    }
  }
}
// a click's features: band levels (dB from its loudest band, floored at -40), the time its energy is 90% in, its energy
function features(x) {
  const re = new Float64Array(N), im = new Float64Array(N);
  let e = 0; for (let i = 0; i < Math.min(N, x.length); i++) { re[i] = x[i]; e += x[i] * x[i]; }
  let acc = 0, dur = x.length; for (let i = 0; i < x.length; i++) { acc += x[i] * x[i]; if (acc >= 0.9 * e) { dur = i + 1; break; } }
  fft(re, im);
  const band = BANDS.map(([lo, hi]) => { let s = 1e-12; for (let k = Math.ceil(lo * N / FS); k <= Math.min(N / 2, Math.floor(hi * N / FS)); k++) s += re[k] * re[k] + im[k] * im[k]; return 10 * Math.log10(s); });
  const top = Math.max(...band);
  return { band: band.map((b) => Math.max(-40, b - top)), dur, e };
}
const dist = (a, b) => { let s = 0; for (let i = 0; i < a.band.length; i++) s += (a.band[i] - b.band[i]) ** 2; return s / a.band.length / 100 + 4 * Math.log(a.dur / b.dur) ** 2; };

// every candidate METAMORF click, at LEVEL 1, int16 scale
const cands = [];
for (let s = 0; s <= 8; s++) for (let t = 0; t <= 127; t += 4) for (let l = 0; l <= 127; l += 5.5) {
  const c = new Click(FS); c.trigger(); const x = [];
  while (c.on) x.push(32767 * c.next(1, s / 8, clickTone(t), clickLen(l)));
  cands.push({ shape: s / 8, tone: t, len: l, ...features(x) });
}
// the old clicks, at volume 1 and rate 1, as the engine played them
const olds = [];
for (let w = 0; w < 12; w++) { const x = []; for (let k = 0; k < 2204; k++) x.push(TRANSIENT_DATA[w * 2205 + k] << 8); olds.push(x); }
for (const d of EXTRA_CLICKS) olds.push(Array.from(d.subarray(0, d.length - 1)));
const map = olds.map((x) => {
  const o = features(x); let best = null, bd = Infinity;
  for (const c of cands) { const d = dist(o, c); if (d < bd) { bd = d; best = c; } }
  const gain = Math.sqrt(o.e / best.e);
  return [best.shape, Math.round(clickTone(best.tone)), +clickLen(best.len).toFixed(3), +gain.toFixed(3)];
});
const out = `// Generated by tools/click-map.mjs, do not edit. Each old sampled click (waves 2..13 the firmware's transients, then
// the 22 extra clicks) as the nearest METAMORF click at the old click's own speed: [SHAPE 0..1, TONE Hz, LENGTH ms,
// LEVEL for the same energy at the old volume 1].
export const CLICK_MAP = ${JSON.stringify(map)};
`;
fs.writeFileSync(new URL('../sound/click-map.js', import.meta.url), out);
map.forEach((m, i) => console.log(i + 2, m.join(' ')));
