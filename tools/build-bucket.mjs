// Bundles the sound bucket (bucket/*.json, one sound each: see sound/bucket.js) into sound/bucket-sounds.js, so the
// page has every sound without a fetch per file. Run after adding sounds (extract-bucket and add-to-bucket run it):
//   node tools/build-bucket.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = new URL('../bucket/', import.meta.url);
const files = readdirSync(dir).filter((f) => /\.json$/i.test(f)).sort();
const sounds = files.map((f) => JSON.parse(readFileSync(new URL(f, dir), 'utf8')));
// kit sounds first (in kit order), then the saved ones (oldest first)
const kitFirst = (s) => (s.from && s.from.startsWith('kits/') ? 0 : 1);
sounds.sort((a, b) => kitFirst(a) - kitFirst(b) || (a.n ?? 0) - (b.n ?? 0) || (a.t ?? 0) - (b.t ?? 0) || a.name.localeCompare(b.name));
writeFileSync(new URL('../sound/bucket-sounds.js', import.meta.url),
  `// Generated by tools/build-bucket.mjs from bucket/. Do not edit.\nexport const BUCKET = [\n${sounds.map((s) => JSON.stringify(s)).join(',\n')}\n];\n`);
console.log(`sound/bucket-sounds.js: ${sounds.length} sounds`);
