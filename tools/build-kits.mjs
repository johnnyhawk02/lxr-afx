// Bundles the kit files in kits/ (.SND: an 8-character name, then one byte per sound parameter) into
// sound/kits.js, so the page can load them without a fetch per file, with each kit's drum names from kits/names.json.
// Run after adding or removing a kit (tools/name-kits.mjs names new kits, then runs this):
//   node tools/build-kits.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const dir = new URL('../kits/', import.meta.url);
const files = readdirSync(dir, { recursive: true }).filter((f) => /\.snd$/i.test(f)).sort();
const list = new URL('names.json', dir), names = existsSync(list) ? JSON.parse(readFileSync(list, 'utf8')) : {};
// drums: the names of drum 1, drum 2, drum 3, snare, cymbal and hihat (none for a kit not named yet)
const kits = files.map((f) => ({ file: f, ...(names[f] ? { drums: names[f].drums } : {}), data: readFileSync(new URL(f, dir)).toString('base64') }));
writeFileSync(new URL('../sound/kits.js', import.meta.url),
  `// Generated by tools/build-kits.mjs from kits/. Do not edit.\nexport const KIT_FILES = ${JSON.stringify(kits, null, 0).replace(/\},\{/g, '},\n{')};\n`);
console.log(`sound/kits.js: ${kits.length} kits`);
